"""Muse Image client: generate a goal scene from the initial scene and a prompt.

Optional extra input for the generator VLM, next to scene-context text. Works for any task
("how should the scene look when the task is done"), not only bowl and plate. Off by default.

Uses the Meta Model API (https://dev.meta.ai/docs/image-generation): `POST /images/edits`
with the initial scene as `images[0]`, or `POST /images/generations` without one. Each image
costs a flat $0.01. Results are cached on disk by request, and a hard cap on images per run
is checked before each uncached call (cached calls are free and do not count).
"""

from __future__ import annotations

import base64
import hashlib
import json
import mimetypes
import os
import time
import urllib.request
from dataclasses import dataclass, field
from pathlib import Path

from ants.synthesizer.llm import META_BASE_URL

GOAL_SCENE_PROMPT = (
    "Edit this robot workspace photo into the same scene at the moment the task is finished. "
    "Keep the camera, table, lighting and every unrelated object unchanged; only move the "
    "objects the task moves. Task: {task}"
)


class ImageBudgetExceeded(RuntimeError):
    """Raised before a call that would start once the per-run image cap is used up."""


def data_url(path: Path) -> str:
    mime = mimetypes.guess_type(path.name)[0] or "image/png"
    return f"data:{mime};base64," + base64.b64encode(path.read_bytes()).decode("ascii")


@dataclass
class ImageGenerator:
    """Image client with a disk cache and a per-run image cap.

    Attributes:
        cache_dir: one image file plus one JSON sidecar per distinct request.
        ledger: JSONL file; one line per call (cached calls are logged as such).
        max_images: maximum uncached images generated by this instance (per run).
    """

    cache_dir: Path
    ledger: Path
    max_images: int = 15
    model: str = "muse-image-1.0"
    base_url: str = META_BASE_URL
    api_key_env: str = "META_API_KEY"
    size: str = "auto"
    output_format: str = "png"
    timeout_s: float = 300.0
    _generated: int = field(default=0, repr=False)

    def goal_scene(self, task: str, initial_scene: Path | None = None, tag: str = "") -> Path:
        """Image of the finished scene for `task`, edited from `initial_scene` when given."""
        return self.generate(GOAL_SCENE_PROMPT.format(task=task), initial_scene, tag)

    def generate(self, prompt: str, source: Path | None = None, tag: str = "") -> Path:
        digest = hashlib.sha256(source.read_bytes()).hexdigest() if source else ""
        key = hashlib.sha256(
            json.dumps([self.model, prompt, digest, self.size, self.output_format]).encode("utf-8")
        ).hexdigest()[:24]
        path = self.cache_dir / f"{key}.{self.output_format}"
        from_cache = path.exists()
        if not from_cache:
            if self._generated >= self.max_images:
                raise ImageBudgetExceeded(f"image cap {self.max_images} per run used up")
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(self._post(prompt, source))
            self._generated += 1
        self.ledger.parent.mkdir(parents=True, exist_ok=True)
        with self.ledger.open("a", encoding="utf-8") as f:
            entry = {
                "time": time.strftime("%Y-%m-%dT%H:%M:%S"),
                "model": self.model,
                "tag": tag,
                "cache_key": key,
                "from_cache": from_cache,
                "prompt": prompt,
                "source": str(source) if source else None,
                "image": str(path),
            }
            f.write(json.dumps(entry) + "\n")
        return path

    def _post(self, prompt: str, source: Path | None) -> bytes:
        body: dict = {
            "model": self.model,
            "prompt": prompt,
            "n": 1,
            "size": self.size,
            "output_format": self.output_format,
        }
        if source is not None:
            body["images"] = [{"image_url": data_url(source)}]
            endpoint = "images/edits"
        else:
            endpoint = "images/generations"
        req = urllib.request.Request(
            f"{self.base_url}/{endpoint}",
            data=json.dumps(body).encode("utf-8"),
            headers={
                "Authorization": f"Bearer {os.environ[self.api_key_env]}",
                "Content-Type": "application/json",
            },
        )
        with urllib.request.urlopen(req, timeout=self.timeout_s) as resp:
            data = json.loads(resp.read().decode("utf-8"))
        return base64.b64decode(data["data"][0]["b64_json"])
